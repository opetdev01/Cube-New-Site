/**
 * Returns Arabic translations for any insight post, falling back to an automatic pre-translated block if missing.
 */
export function getInsightArabicContent(item: any): { titleAr: string; excerptAr: string; contentAr: string } {
  if (item.titleAr && item.contentAr) {
    return {
      titleAr: item.titleAr,
      excerptAr: item.excerptAr || item.excerpt,
      contentAr: item.contentAr
    };
  }

  const found = INSIGHT_ARABIC_TRANSLATIONS[item.slug];
  if (found) {
    return found;
  }

  // Clean fallback for items not in explicit map
  const cleanTitle = item.title;
  const cleanExcerpt = item.excerpt || "مقالة وإشعاع معماري وتخطيطي يقدم رؤية كيو ب للاستشارات نحو استدامة البيئة المبنية.";
  const cleanBody = item.content && !item.content.includes("i0.wp.com")
    ? item.content 
    : `<p>${cleanExcerpt}</p><p>تقدم كيو ب للاستشارات حلولاً هندسية وتخطيطية معاصرة تهدف إلى تطوير البيئة العمرانية والارتقاء بجودة الحياة وفقاً لأعلى المعايير العالمية.</p>`;

  return {
    titleAr: cleanTitle,
    excerptAr: cleanExcerpt,
    contentAr: cleanBody
  };
}
